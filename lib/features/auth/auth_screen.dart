  Future<void> _finishSocialSignIn({
    required String provider,
    String? email,
    String? name,
    String? username,
    bool isNewAccount = false,
    bool showPopup = true,
  }) async {
    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    final success = await AuthService.instance.loginWithSocial(
      provider: provider,
      email: email,
      name: name,
    );
    if (!mounted) return;

    if (success) {
      final resolvedEmail = AuthService.instance.userEmail;
      final resolvedName = AuthService.instance.userName;
      final effectiveUsername = (username != null && username.trim().isNotEmpty)
          ? username.trim()
          : (isNewAccount
              ? await AuthService.instance.generateUniqueUsernameFromEmail(resolvedEmail)
              : resolvedName);

      if (isNewAccount && resolvedEmail.isNotEmpty) {
        // Reserve this unique username in Supabase so no other user can take the same username
        unawaited(
          AuthService.instance.linkUsernameToEmailAccount(
            username: effectiveUsername,
            email: resolvedEmail,
            password: 'google_oauth_${resolvedEmail.hashCode}',
            displayName: resolvedName.isNotEmpty ? resolvedName : effectiveUsername,
          ),
        );
      }

      if (!mounted) return;
      try {
        final state = Provider.of<AppState>(context, listen: false);
        await state.loadAccountOnLogin(
          name: resolvedName.isNotEmpty ? resolvedName : effectiveUsername,
          email: resolvedEmail,
          isNewAccount: isNewAccount,
        );
      } catch (_) {}
      if (!mounted) return;

      setState(() {
        _isLoading = false;
        _isSuccess = true;
      });
      SoundService.instance.play(isNewAccount ? Sfx.levelComplete : Sfx.welcome);

      if (showPopup) {
        await _showAuthStatusDialog(
          icon: isNewAccount ? Icons.celebration_rounded : Icons.verified_rounded,
          accentColor: AppColors.successGreen,
          title: isNewAccount ? 'Welcome to Quixoria!' : 'Welcome Back!',
          message: isNewAccount
              ? 'Signed up successfully with Google! Your reading adventure and cloud save are ready.'
              : 'Signed in successfully with Google! Your saved progress, purchases, and streak have been restored.',
          accountUsername: isNewAccount ? effectiveUsername : AuthService.instance.userName,
          accountEmail: resolvedEmail,
          primaryLabel: isNewAccount ? 'Start My Quest' : 'Continue',
        );
      }
      if (!mounted) return;
      widget.onAuthSuccess();
    } else {
      setState(() {
        _isLoading = false;
        _errorMessage = 'Could not sign in with $provider. Please try again.';
      });
      SoundService.instance.play(Sfx.tap);
    }
  }

