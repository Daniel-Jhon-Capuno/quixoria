  Widget _buildPasswordStrengthWidget(String password) {
    if (password.isEmpty) return const SizedBox.shrink();
    final len = password.length;
    final hasMinLen = len >= 6;
    final hasMix = RegExp(r'[0-9!@#\$%^&*(),.?":{}|<>]').hasMatch(password) &&
        RegExp(r'[a-zA-Z]').hasMatch(password);

    int strengthLevel;
    if (!hasMinLen) {
      strengthLevel = 1;
    } else if (!hasMix || len < 8) {
      strengthLevel = 2;
    } else {
      strengthLevel = 3;
    }

    Color strengthColor;
    String strengthLabel;
    switch (strengthLevel) {
      case 1:
        strengthColor = AppColors.vermillion;
        strengthLabel = 'Too Short (Min. 6 Characters)';
        break;
      case 2:
        strengthColor = AppColors.antiqueGold;
        strengthLabel = 'Good Password';
        break;
      case 3:
      default:
        strengthColor = AppColors.successGreen;
        strengthLabel = 'Strong Password';
        break;
    }

    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 4, vertical: 2),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              for (int i = 1; i <= 3; i++) ...[
                Expanded(
                  child: AnimatedContainer(
                    duration: const Duration(milliseconds: 250),
                    height: 3.5,
                    margin: EdgeInsets.only(right: i < 3 ? 4 : 0),
                    decoration: BoxDecoration(
                      color: i <= strengthLevel ? strengthColor : Colors.grey.withValues(alpha: 0.22),
                      borderRadius: BorderRadius.circular(2),
                    ),
                  ),
                ),
              ],
            ],
          ),
          const SizedBox(height: 4),
          Row(
            children: [
              Icon(
                strengthLevel >= 2 ? Icons.shield_rounded : Icons.shield_outlined,
                size: 12,
                color: strengthColor,
              ),
              const SizedBox(width: 4),
              Expanded(
                child: Text(
                  strengthLabel,
                  maxLines: 1,
                  overflow: TextOverflow.ellipsis,
                  style: TextStyle(
                    fontSize: 10.5,
                    fontWeight: FontWeight.w600,
                    color: strengthColor,
                  ),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }

  Future<void> _handleSendCode() async {
    setState(() {
      _submitted = true;
      _usernameTakenError = null;
      _errorWaveTrigger++;
    });
    final password = _passwordController.text.trim();
    final email = _emailController.text.trim();
    if (!_isValidEmail(email)) {
      setState(() {
        _errorMessage = email.isEmpty
            ? 'Please enter your email address.'
            : 'Please enter a valid email address.';
      });
      SoundService.instance.play(Sfx.tap);
      return;
    }
    if (password.length < 6) {
      setState(() {
        _errorMessage = password.isEmpty
            ? 'Please enter a password.'
            : 'Password must be at least 6 characters (currently ${password.length}/6).';
      });
      SoundService.instance.play(Sfx.tap);
      return;
    }
    if (!_acceptedTerms) {
      setState(() => _errorMessage = 'Please accept the Terms & Conditions to sign up.');
      SoundService.instance.play(Sfx.tap);
      return;
    }

    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    SoundService.instance.play(Sfx.tap);

    // Enforce unique username; if left empty, auto-generate a unique handle similar to the email
    var chosenUsername = _nameController.text.trim();
    _usernameWasAutoGenerated = false;
    if (chosenUsername.isNotEmpty) {
      final taken = await AuthService.instance.isUsernameTaken(
        chosenUsername,
        ignoreEmail: email,
      );
      if (!mounted) return;
      if (taken) {
        setState(() {
          _isLoading = false;
          _errorWaveTrigger++;
          _usernameTakenError = 'This username is already taken. Please choose a different one.';
          _errorMessage = 'That username is already in use. Please pick another username.';
        });
        SoundService.instance.play(Sfx.tap);
        return;
      }
    } else {
      chosenUsername = await AuthService.instance.generateUniqueUsernameFromEmail(email);
      if (!mounted) return;
      _usernameWasAutoGenerated = true;
      _nameController.text = chosenUsername;
    }

    final result = await AuthService.instance.signUpWithEmailDetailed(
      email: email,
      password: password,
      name: chosenUsername,
      acceptedTerms: _acceptedTerms,
    );

    if (!mounted) return;
    if (!result.success) {
      setState(() {
        _isLoading = false;
        _errorMessage = result.errorMessage ?? 'Could not sign up. Please try again.';
      });
      SoundService.instance.play(Sfx.tap);
      return;
    }

    if (chosenUsername.isNotEmpty) {
      // Link username alias so the user can log in with either Email or Username later
      unawaited(
        AuthService.instance.linkUsernameToEmailAccount(
          username: chosenUsername,
          email: email,
          password: password,
          displayName: chosenUsername,
        ),
      );
    }

    // If Supabase issued an instant session (email confirmation disabled), enter immediately!
    if (!result.needsEmailVerification) {
      try {
        final state = Provider.of<AppState>(context, listen: false);
        await state.loadAccountOnLogin(
          name: AuthService.instance.userName,
          email: AuthService.instance.userEmail,
          isNewAccount: true,
        );
      } catch (_) {}
      if (!mounted) return;
      setState(() {
        _isLoading = false;
        _isSuccess = true;
      });
      SoundService.instance.play(Sfx.levelComplete);
      await Future.delayed(const Duration(milliseconds: 500));
      if (!mounted) return;
      widget.onAuthSuccess();
      return;
    }

    setState(() {
      _isLoading = false;
      _dispatchedCode = result.fallbackCode;
      _isVerifyingCode = true;
      _tabSlideDirection = 1;
    });
    SoundService.instance.play(Sfx.reward);
  }

  Future<void> _handleResendCode() async {
    final email = _emailController.text.trim();
    if (!_isValidEmail(email)) return;
    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });
    final res = await AuthService.instance.resendVerificationCode(email);
    if (!mounted) return;
    setState(() {
      _isLoading = false;
      if (res.fallbackCode != null) {
        _dispatchedCode = res.fallbackCode;
      }
      if (!res.success) {
        _errorMessage = res.errorMessage ?? 'Could not resend verification code.';
      }
    });
    if (res.success) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('A fresh verification code was sent to $email.'),
          backgroundColor: AppColors.successGreen,
        ),
      );
    }
  }

  Future<void> _handleVerifyCode() async {
    final code = _otpController.text.replaceAll(RegExp(r'\s+'), '').trim();
    if (code.length < 6 || code.length > 8) {
      setState(() => _errorMessage = 'Please enter the verification code (6 to 8 digits).');
      SoundService.instance.play(Sfx.tap);
      return;
    }

    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    final result = await AuthService.instance.verifyAndRegisterDetailed(
      email: _emailController.text,
      code: code,
      name: _nameController.text,
      acceptedTerms: _acceptedTerms,
      password: _passwordController.text,
    );

    if (!mounted) return;

    if (result.success) {
      try {
        final state = Provider.of<AppState>(context, listen: false);
        final regName = _nameController.text.trim().isNotEmpty
            ? _nameController.text.trim()
            : AuthService.instance.userName;
        final regEmail = _emailController.text.trim().isNotEmpty
            ? _emailController.text.trim()
            : AuthService.instance.userEmail;
        await state.loadAccountOnLogin(
          name: regName,
          email: regEmail,
          isNewAccount: true,
        );
      } catch (_) {}

      if (!mounted) return;
      setState(() {
        _isLoading = false;
        _isSuccess = true;
      });
      SoundService.instance.play(Sfx.levelComplete);
      final finalName = _nameController.text.trim().isNotEmpty
          ? _nameController.text.trim()
          : AuthService.instance.userName;
      final finalEmail = _emailController.text.trim().isNotEmpty
          ? _emailController.text.trim()
          : AuthService.instance.userEmail;
      if (_usernameWasAutoGenerated) {
        final chosen = await _showChooseUsernameDialog(
          email: finalEmail,
          suggestedUsername: finalName,
          isGoogle: false,
        );
        if (!mounted) return;
        if (chosen != null && chosen.trim().isNotEmpty && chosen.trim() != finalName) {
          final updated = chosen.trim();
          await AuthService.instance.updateDisplayName(updated);
          await AuthService.instance.linkUsernameToEmailAccount(
            username: updated,
            email: finalEmail,
            password: _passwordController.text.trim(),
            displayName: updated,
          );
          if (mounted) {
            try {
              final state = Provider.of<AppState>(context, listen: false);
              state.updateUserProfile(name: updated, email: finalEmail);
            } catch (_) {}
          }
        }
      } else {
        await _showAuthStatusDialog(
          icon: Icons.celebration_rounded,
          accentColor: AppColors.successGreen,
          title: 'Welcome to Quixoria!',
          message: 'Your account has been created successfully. Your progress and purchases will now auto-save to the cloud!',
          accountUsername: finalName,
          accountEmail: finalEmail,
          primaryLabel: 'Start My Quest',
        );
      }
      if (!mounted) return;
      widget.onAuthSuccess();
    } else {
      setState(() {
        _isLoading = false;
        _errorMessage = result.errorMessage ?? 'Invalid verification code. Please check your email code and try again.';
      });
      SoundService.instance.play(Sfx.tap);
    }
  }

  Future<void> _handleLogin() async {
    setState(() {
      _loginSubmitted = true;
      _errorWaveTrigger++;
    });
    final identifier = _emailController.text.trim();
    final password = _passwordController.text.trim();

    if (identifier.isEmpty) {
      setState(() {
        _errorMessage = 'Please enter your email or username.';
      });
      SoundService.instance.play(Sfx.tap);
      return;
    }
    if (identifier.contains('@') && !identifier.startsWith('@') && !_isValidEmail(identifier)) {
      setState(() {
        _errorMessage = 'Please enter a valid email address.';
      });
      SoundService.instance.play(Sfx.tap);
      return;
    }
    if (password.isEmpty) {
      setState(() => _errorMessage = 'Please enter your password.');
      SoundService.instance.play(Sfx.tap);
      return;
    }

    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });

    final result = await AuthService.instance.loginWithIdentifier(
      identifier: identifier,
      password: password,
      rememberMe: _rememberMe,
    );

    if (!mounted) return;

    if (result.success) {
      try {
        final state = Provider.of<AppState>(context, listen: false);
        final resolvedEmail = AuthService.instance.userEmail;
        final resolvedName = AuthService.instance.userName.isNotEmpty
            ? AuthService.instance.userName
            : (resolvedEmail.contains('@') ? resolvedEmail.split('@').first : identifier);
        await state.loadAccountOnLogin(
          name: resolvedName,
          email: resolvedEmail,
          isNewAccount: false,
        );
      } catch (_) {}

      if (!mounted) return;
      setState(() {
        _isLoading = false;
        _isSuccess = true;
      });
      SoundService.instance.play(Sfx.welcome);
      await _showAuthStatusDialog(
        icon: Icons.verified_rounded,
        accentColor: AppColors.successGreen,
        title: 'Welcome Back!',
        message: 'Logged in successfully. Your cloud progress, Caballero Pass, gems, and streak are synced!',
        accountUsername: AuthService.instance.userName,
        accountEmail: AuthService.instance.userEmail,
        primaryLabel: 'Continue',
      );
      if (!mounted) return;
      widget.onAuthSuccess();
    } else {
      setState(() {
        _isLoading = false;
        _errorMessage = result.errorMessage ?? 'Unable to log in. Please check your email/username and password.';
      });
      SoundService.instance.play(Sfx.tap);
    }
  }

  Future<void> _handleSocialLogin(String provider) async {
    HapticFeedback.mediumImpact();
    SoundService.instance.play(Sfx.tap);

    if (provider == 'Google') {
      setState(() {
        _isLoading = true;
        _errorMessage = null;
      });

      // 1. If Google OAuth is enabled on Supabase, launch the real Google OAuth browser flow
      final oauthEnabled = await SupabaseService.instance.isGoogleOAuthEnabled();
      if (!mounted) return;
      if (oauthEnabled) {
        final oauthUri = SupabaseService.instance.buildGoogleOAuthUri();
        final launched = await launchUrl(
          oauthUri,
          mode: LaunchMode.externalApplication,
        );
        if (!mounted) return;
        if (launched) {
          // Deep link listener (_completeGoogleOAuthCallback) will finish sign-in on redirect
          setState(() => _isLoading = false);
          return;
        }
      }

      // 2. Otherwise open the crisp Google Account Picker sheet so the user signs in with their real Gmail
      //    and automatically restores their Supabase cloud backup (Caballero Pass, cosmetics, gems, streak).
      setState(() => _isLoading = false);
      final chosen = await _showGoogleAccountPickerSheet();
      if (!mounted || chosen == null) return;
      await _finishSocialSignIn(
        provider: 'Google',
        email: chosen['email']!,
        name: chosen['name'] ?? '',
      );
      return;
    }

    await _finishSocialSignIn(provider: provider);
  }

