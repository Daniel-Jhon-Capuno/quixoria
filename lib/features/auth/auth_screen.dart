  void _initOAuthDeepLinkListener() {
    if (kIsWeb) return;
    try {
      final appLinks = AppLinks();
      // 1. Handle cold-start deep link (if Android recreated Activity on OAuth return)
      appLinks.getInitialLink().then((uri) {
        if (uri != null &&
            uri.scheme == 'com.example.quixoria' &&
            uri.host == 'login-callback') {
          _completeGoogleOAuthCallback(uri);
        }
      }).catchError((_) {});

      // 2. Handle warm-start deep link stream
      _oauthLinkSub = appLinks.uriLinkStream.listen((uri) {
        if (uri.scheme == 'com.example.quixoria' && uri.host == 'login-callback') {
          _completeGoogleOAuthCallback(uri);
        }
      }, onError: (_) {});
    } catch (_) {
      // Safe fallback in headless/test environments without native deep-link channel
    }
  }

