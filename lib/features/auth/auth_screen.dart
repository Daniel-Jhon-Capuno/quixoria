  Future<void> _completeGoogleOAuthCallback(Uri callbackUri) async {
    if (!mounted || _handlingOAuthCallback) return;
    _handlingOAuthCallback = true;
    setState(() {
      _isLoading = true;
      _errorMessage = null;
    });
    try {
      final user = await SupabaseService.instance.completeOAuthCallback(callbackUri);
      if (!mounted) return;
      final email = (user?.email ?? user?.userMetadata?['email']?.toString() ?? '').trim().toLowerCase();
      if (user == null || email.isEmpty) {
        setState(() {
          _isLoading = false;
          _errorMessage = 'Could not read your Google email. Please try signing in again.';
        });
        return;
      }

      final rawGoogleName = (user.userMetadata?['full_name'] ??
              user.userMetadata?['name'] ??
              '')
          .toString()
          .trim();

      // Detect whether this Gmail already has an existing Quixoria account/cloud save
      final hasCloudData = await SupabaseService.instance.hasExistingCloudAccount(email);
      final createdAt = DateTime.tryParse(user.createdAt);
      final isOlderAuthUser = createdAt != null &&
          DateTime.now().toUtc().difference(createdAt.toUtc()).inSeconds > 90;
      final accountAlreadyExists = hasCloudData || isOlderAuthUser;

      if (!mounted) return;
      setState(() => _isLoading = false);

      if (_isSignUp && accountAlreadyExists) {
        // Smart handling: user clicked Sign in with Google on Sign Up, but Gmail already exists!
        final proceedLogin = await _showAuthStatusDialog(
          icon: Icons.verified_user_rounded,
          accentColor: AppColors.antiqueGold,
          title: 'Account Already Registered!',
          message:
              'This Google account is already signed up in Quixoria. We found your saved account — would you like to log in right now?',
          accountEmail: email,
          primaryLabel: 'Log In to My Account',
          secondaryLabel: 'Cancel',
        );
        if (!mounted) return;
        if (proceedLogin != true) {
          await AuthService.instance.logout();
          return;
        }
        await _finishSocialSignIn(
          provider: 'Google',
          email: email,
          name: rawGoogleName,
          isNewAccount: false,
          showPopup: false,
        );
        return;
      }

      if (!_isSignUp && !accountAlreadyExists) {
        // Smart handling: user clicked Sign in with Google on Log In, but Gmail has no account yet!
        final createNow = await _showAuthStatusDialog(
          icon: Icons.person_add_alt_1_rounded,
          accentColor: AppColors.streakOrange,
          title: 'No Account Found',
          message:
              'Sorry, this Google account does not have a Quixoria account yet. Would you like to sign up with it now?',
          accountEmail: email,
          primaryLabel: 'Sign Up with This Google Account',
          secondaryLabel: 'Use Another Account',
        );
        if (!mounted) return;
        if (createNow != true) {
          await AuthService.instance.logout();
          return;
        }
        final suggestedUsername = await AuthService.instance.generateUniqueUsernameFromEmail(email);
        if (!mounted) return;
        final chosenUsername = await _showChooseUsernameDialog(
          email: email,
          suggestedUsername: suggestedUsername,
          isGoogle: true,
        );
        if (!mounted || chosenUsername == null) return;
        await _finishSocialSignIn(
          provider: 'Google',
          email: email,
          name: chosenUsername,
          username: chosenUsername,
          isNewAccount: true,
          showPopup: false,
        );
        return;
      }

      if (accountAlreadyExists) {
        // Log In with existing Google account
        await _finishSocialSignIn(
          provider: 'Google',
          email: email,
          name: rawGoogleName,
          isNewAccount: false,
          showPopup: true,
        );
      } else {
        // Fresh Sign Up with Google account -> prompt player to customize or confirm their unique username
        final suggestedUsername = await AuthService.instance.generateUniqueUsernameFromEmail(email);
        if (!mounted) return;
        final chosenUsername = await _showChooseUsernameDialog(
          email: email,
          suggestedUsername: suggestedUsername,
          isGoogle: true,
        );
        if (!mounted || chosenUsername == null) return;
        await _finishSocialSignIn(
          provider: 'Google',
          email: email,
          name: chosenUsername,
          username: chosenUsername,
          isNewAccount: true,
          showPopup: false,
        );
      }
    } finally {
      _handlingOAuthCallback = false;
    }
  }

