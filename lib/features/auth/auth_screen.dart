class _MotionTextFieldState extends State<_MotionTextField>
    with SingleTickerProviderStateMixin {
  late FocusNode _focusNode;
  late AnimationController _waveController;
  Timer? _waveHideTimer;
  bool _showErrorWave = false;
  String _lastObservedText = '';

  @override
  void initState() {
    super.initState();
    _focusNode = FocusNode();
    _lastObservedText = widget.controller.text;
    _waveController = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 1600),
    );

    if (widget.errorText != null && widget.errorText!.isNotEmpty) {
      _triggerErrorWave();
    }

    _focusNode.addListener(() {
      if (mounted) setState(() {});
    });
    widget.controller.addListener(_handleTextChange);
  }

  void _handleTextChange() {
    if (!mounted) return;
    final currentText = widget.controller.text;
    final textChanged = currentText != _lastObservedText;
    _lastObservedText = currentText;
    if (textChanged && widget.errorText != null && widget.errorText!.isNotEmpty) {
      _triggerErrorWave();
    } else {
      setState(() {});
    }
  }

  void _triggerErrorWave() {
    _waveHideTimer?.cancel();
    if (!_showErrorWave) {
      setState(() => _showErrorWave = true);
    }
    if (!_waveController.isAnimating) {
      _waveController.repeat();
    }
    _waveHideTimer = Timer(const Duration(milliseconds: 2800), () {
      if (!mounted) return;
      _waveController.stop();
      setState(() => _showErrorWave = false);
    });
  }

  void _clearErrorWave() {
    _waveHideTimer?.cancel();
    if (_waveController.isAnimating) {
      _waveController.stop();
    }
    if (_showErrorWave) {
      setState(() => _showErrorWave = false);
    }
  }

  @override
  void didUpdateWidget(covariant _MotionTextField oldWidget) {
    super.didUpdateWidget(oldWidget);
    final hasErr = widget.errorText != null && widget.errorText!.isNotEmpty;
    final hadErr = oldWidget.errorText != null && oldWidget.errorText!.isNotEmpty;
    final errorChanged = widget.errorText != oldWidget.errorText;
    final triggerBumped = widget.errorTrigger != oldWidget.errorTrigger;

    if (!hasErr) {
      _clearErrorWave();
    } else if (!hadErr || errorChanged || triggerBumped) {
      _triggerErrorWave();
    }
  }

  @override
  void dispose() {
    _waveHideTimer?.cancel();
    widget.controller.removeListener(_handleTextChange);
    if (_focusNode.hasFocus) {
      _focusNode.unfocus();
    }
    _focusNode.dispose();
    _waveController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isFocused = _focusNode.hasFocus;
    final effectiveHasError = widget.errorText != null && widget.errorText!.isNotEmpty;

    final primaryGold = AppColors.antiqueGold;
    final errorColor = AppColors.vermillion;
    final activeColor = effectiveHasError ? errorColor : primaryGold;

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        // Persistent, Always-Visible Field Label
        Padding(
          padding: const EdgeInsets.only(left: 4, bottom: 6),
          child: Text(
            widget.label,
            style: AppTypography.labelMedium.copyWith(
              fontSize: 12.5,
              fontWeight: FontWeight.w800,
              color: effectiveHasError
                  ? errorColor
                  : (isFocused ? activeColor : theme.colorScheme.onSurface.withValues(alpha: 0.85)),
              letterSpacing: 0.2,
            ),
          ),
        ),
        // Clean Rounded Input Container
        AnimatedContainer(
          duration: const Duration(milliseconds: 220),
          curve: Curves.easeOutCubic,
          decoration: BoxDecoration(
            color: isFocused
                ? activeColor.withValues(alpha: 0.08)
                : theme.colorScheme.surface,
            borderRadius: BorderRadius.circular(18),
            border: Border.all(
              color: effectiveHasError
                  ? errorColor
                  : (isFocused
                      ? activeColor
                      : theme.dividerColor.withValues(alpha: 0.5)),
              width: (isFocused || effectiveHasError) ? 2.0 : 1.6,
            ),
            boxShadow: isFocused
                ? [
                    BoxShadow(
                      color: activeColor.withValues(alpha: 0.18),
                      blurRadius: 10,
                      offset: const Offset(0, 2),
                    ),
                  ]
                : [],
          ),
          clipBehavior: Clip.antiAlias,
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Padding(
                padding: EdgeInsets.only(
                  left: 14,
                  right: widget.suffix != null ? 8 : 14,
                  top: 4,
                  bottom: 4,
                ),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.center,
                  children: [
                    Icon(
                      widget.icon,
                      size: 20,
                      color: effectiveHasError
                          ? errorColor
                          : (isFocused
                              ? activeColor
                              : theme.colorScheme.onSurface.withValues(alpha: 0.6)),
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: TextField(
                        controller: widget.controller,
                        focusNode: _focusNode,
                        obscureText: widget.obscureText,
                        keyboardType: widget.keyboardType,
                        onChanged: widget.onChanged,
                        style: AppTypography.bodyMedium.copyWith(
                          fontSize: 14.5,
                          fontWeight: FontWeight.w700,
                          color: theme.colorScheme.onSurface,
                        ),
                        decoration: InputDecoration(
                          isDense: true,
                          filled: false,
                          border: InputBorder.none,
                          enabledBorder: InputBorder.none,
                          focusedBorder: InputBorder.none,
                          contentPadding: const EdgeInsets.symmetric(vertical: 11),
                          hintText: widget.hint,
                          hintStyle: AppTypography.bodySmall.copyWith(
                            color: theme.colorScheme.onSurface.withValues(alpha: 0.45),
                            fontSize: 13.5,
                          ),
                        ),
                      ),
                    ),
                    if (widget.suffix != null) widget.suffix!,
                  ],
                ),
              ),

              // Zigzag Error Wave — ONLY shown on an input error, then fades away smoothly after 2.8s
              AnimatedSize(
                duration: const Duration(milliseconds: 260),
                curve: Curves.easeOutCubic,
                child: AnimatedOpacity(
                  duration: const Duration(milliseconds: 260),
                  opacity: (effectiveHasError && _showErrorWave) ? 1.0 : 0.0,
                  child: (effectiveHasError && _showErrorWave)
                      ? AnimatedBuilder(
                          animation: _waveController,
                          builder: (context, _) {
                            return SizedBox(
                              height: 4,
                              child: CustomPaint(
                                painter: _ZigzagPainter(
                                  color: errorColor,
                                  phase: _waveController.value,
                                ),
                                child: Container(),
                              ),
                            );
                          },
                        )
                      : const SizedBox.shrink(),
                ),
              ),
            ],
          ),
        ),

        // Helper widget (e.g. password strength)
        if (widget.helperWidget != null) ...[
          const SizedBox(height: 4),
          widget.helperWidget!,
        ],

        // Error text display
        if (effectiveHasError) ...[
          const SizedBox(height: 4),
          Padding(
            padding: const EdgeInsets.only(left: 12),
            child: Text(
              widget.errorText!,
              style: TextStyle(
                color: errorColor,
                fontSize: 11,
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
        ],
      ],
    );
  }
}

class _ZigzagPainter extends CustomPainter {
  final Color color;
  final double phase;

  _ZigzagPainter({required this.color, required this.phase});

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = color
      ..strokeWidth = 1.8
      ..style = PaintingStyle.stroke;

    final path = Path();
    const toothWidth = 8.0;
    const toothHeight = 3.0;
    final offset = phase * toothWidth * 2;

    double x = -toothWidth * 2 + (offset % (toothWidth * 2));
    path.moveTo(x, size.height);

    while (x < size.width + toothWidth * 2) {
      path.lineTo(x + toothWidth / 2, size.height - toothHeight);
      path.lineTo(x + toothWidth, size.height);
      x += toothWidth;
    }

    canvas.clipRect(Rect.fromLTWH(0, 0, size.width, size.height));
    canvas.drawPath(path, paint);
  }

  @override
  bool shouldRepaint(covariant _ZigzagPainter oldDelegate) =>
      oldDelegate.phase != phase || oldDelegate.color != color;
}

